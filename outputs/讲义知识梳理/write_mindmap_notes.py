def put_note(knowledge: str, data: dict) -> dict:
    content = "@mindmap\n" + json.dumps(data, ensure_ascii=False, indent=1)
    payload = json.dumps({
        "note_type": "knowledge",
        "compulsory": COMPULSORY,
        "chapter": CHAPTER,
        "knowledge": knowledge,
        "content": content,
    }, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(
        BASE + "/api/lecture/notes",
        data=payload,
        method="PUT",
        headers={"Content-Type": "application/json", "X-Local-Token": TOKEN},
    )
    with urllib.request.urlopen(req, timeout=20) as resp:
        return json.loads(resp.read().decode("utf-8"))


def main() -> None:
    print("target:", BASE, "chapter:", CHAPTER, "sections:", len(NOTES))
    for knowledge, data in NOTES.items():
        row = put_note(knowledge, data)
        print("OK", row.get("note_key"), "branches=", len(data["branches"]))
    print("written:", len(NOTES))


if __name__ == "__main__":
    main()
